#!/usr/bin/env python3
"""Generate compact Unicode tables for the Qwen2 byte-level BPE tokenizer.

The generated header stores inclusive codepoint ranges for the Unicode general
categories Letter (L*) and Number (N*), plus the Unicode White_Space set used by
llama.cpp's qwen2 pre-tokenizer.
"""

import argparse
import pathlib
import unicodedata

MAX_CODEPOINT = 0x110000
WHITESPACE = [
    0x0009, 0x000A, 0x000B, 0x000C, 0x000D, 0x0020, 0x0085, 0x00A0,
    0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000,
]


def ranges_for(predicate):
    ranges = []
    start = None
    for codepoint in range(MAX_CODEPOINT):
        matched = predicate(codepoint)
        if matched and start is None:
            start = codepoint
        elif not matched and start is not None:
            ranges.append((start, codepoint - 1))
            start = None
    if start is not None:
        ranges.append((start, MAX_CODEPOINT - 1))
    return ranges


def emit_ranges(name, ranges):
    lines = [f"static const BnneUnicodeRange {name}[] = {{"]
    for first, last in ranges:
        lines.append(f"    {{0x{first:06X}u, 0x{last:06X}u}},")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="bnn-sw-v2/tokenizer/unicode-data.h")
    args = parser.parse_args()

    letters = ranges_for(
        lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    numbers = ranges_for(
        lambda cp: unicodedata.category(chr(cp)).startswith("N"))

    content = [
        "/* Generated by tools/gen-unicode-tables.py. Do not edit. */",
        f"/* Unicode data version: {unicodedata.unidata_version} */",
        "#ifndef BNNE_UNICODE_DATA_H",
        "#define BNNE_UNICODE_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t first;",
        "    uint32_t last;",
        "} BnneUnicodeRange;",
        "",
        emit_ranges("bnne_unicode_letters", letters),
        "",
        emit_ranges("bnne_unicode_numbers", numbers),
        "",
        "static const uint32_t bnne_unicode_whitespace[] = {",
    ]
    for index in range(0, len(WHITESPACE), 8):
        chunk = ", ".join(f"0x{cp:04X}u" for cp in WHITESPACE[index:index + 8])
        content.append(f"    {chunk},")
    content.extend([
        "};",
        "",
        "#endif",
        "",
    ])

    path = pathlib.Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(content), encoding="utf-8")
    print(f"wrote {path}: {len(letters)} letter ranges, {len(numbers)} number ranges, "
          f"{len(WHITESPACE)} whitespace codepoints (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
